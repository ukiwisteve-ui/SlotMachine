"""Rebuild the "Preview landscape" CSS from the real landscape media query in www/index.html.
Every rule is copied under html.force-land, with viewport units swapped for --lw/--lh (the preview screen's size).
Run after changing the landscape layout: python3 tools/landscape_preview.py"""
import re
p = 'www/index.html'
s = open(p).read()
pa = s.find('/* Landscape preview')
if pa >= 0:
    s = s[:pa] + s[s.index('/* end landscape preview */', pa) + len('/* end landscape preview */\n'):]
a = s.index('@media (orientation: landscape) and (max-height: 560px) {')
bs = s.index('{', a) + 1; depth = 1; i = bs
while depth:
    depth += {'{': 1, '}': -1}.get(s[i], 0); i += 1
def units(d):
    d = re.sub(r'([\d.]+)dvh', lambda m: 'calc(var(--lh) * %s / 100)' % m.group(1), d)
    return re.sub(r'([\d.]+)vw', lambda m: 'calc(var(--lw) * %s / 100)' % m.group(1), d)
out = []
for part in re.findall(r'[^{}]+\{[^}]*\}', s[bs:i - 1]):
    m = re.match(r'\s*([^{]+)\{(.*)\}', part, re.S)
    sel = ', '.join('html.force-land ' + x.strip() for x in m.group(1).split(','))
    out.append('%s {%s}' % (sel, units(m.group(2))))
block = '''/* Landscape preview (Settings > Test features). On a portrait phone the game turns sideways;
   on a computer it shows inside a landscape phone-sized screen. Generated by tools/landscape_preview.py. */
html.force-land { --lw: 100vh; --lh: 100vw; }
html.force-land body { position: absolute; top: 0; left: 0; width: var(--lw); height: var(--lh); transform-origin: top left; transform: rotate(90deg) translateY(-100%); }
html.force-land.desk { --lw: 880px; --lh: 400px; background: #05010c; }
html.force-land.desk body { top: 50%; left: 50%; transform-origin: center; transform: translate(-50%, -50%) scale(var(--fit, 1)); border-radius: 26px; box-shadow: 0 0 0 10px #111, 0 0 0 12px #333, 0 20px 60px #000; }
html.force-land .rotate-hint { display: none !important; }
''' + '\n'.join(out) + '\n/* end landscape preview */\n'
s = s[:i] + '\n' + block + s[i:]
open(p, 'w').write(s)
print('rules', len(out))
